import spacy

# Загружаем модель
nlp = spacy.load("en_core_web_sm")

# Способ 1: Получить все уникальные теги из словаря модели (надежно)
# Мы можем обратиться к nlp.vocab.strings, но там много лишнего.
# Лучше использовать встроенный метод объяснения тегов, если он есть, 
# или просто собрать их из обучающих данных модели (если доступны).

# Самый простой практический способ для английского (Penn Treebank):
# Модель хранит映射 (mapping) между тегами и описанием.
# Но если нужно просто вывести список всех tag_, которые модель может выдать:

unique_tags = set()

# Прогоним небольшой тестовый текст, содержащий разные конструкции, 
# чтобы "разбудить" все возможные теги в словаре, ИЛИ используем vocab
# Но самый верный способ для en_core_web_sm — посмотреть в nlp.pipe_labels или документации.

# В новых версиях SpaCy можно попробовать так:
if "tagger" in nlp.pipe_names:
    tagger = nlp.get_pipe("tagger")
    # Получаем названия классов, которым обучен таггер
    labels = tagger.labels
    unique_tags = list(labels)
    
    print(f"Количество уникальных тегов в модели: {len(unique_tags)}")
    print("Список всех тегов (tag_):")
    for tag in sorted(unique_tags):
        # Можно получить описание тега через explain()
        description = spacy.explain(tag)
        print(f"{tag}: {description}")
else:
    print("Таггер не найден в пайплайне.")